    IReadOnlyList<DlMpNetObjectField> Fields);

public sealed class DlMpNetObjectCatalog
{
    public DlMpNetObjectSummary? CreateSummary(uint pointer, string? dataType)
    {
        if (pointer == 0 || string.IsNullOrWhiteSpace(dataType))
        {
            return null;
        }

        if (string.Equals(dataType, "Hero", StringComparison.OrdinalIgnoreCase))
        {
            return new DlMpNetObjectSummary(
                Pointer: pointer,
                DataType: "Hero",
                ByteCount: DlMpHeroNetObject.ByteCount,
                Fields: DlMpHeroNetObject.Fields);
        }

        return null;
    }
}

